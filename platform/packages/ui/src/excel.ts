// A date becomes YYYY-MM-DD (plus the time if any), a number or boolean its text.
const cellText = (v: unknown): string => {
  if (v == null) return "";
  if (v instanceof Date) {
    const iso = v.toISOString();
    return iso.endsWith("T00:00:00.000Z") ? iso.slice(0, 10) : iso.slice(0, 16).replace("T", " ");
  }
  return String(v);
};

// Every sheet as rows of cell texts (empty cells are "").
export async function readXlsx(buffer: ArrayBuffer): Promise<Record<string, string[][]>> {
  // Loaded when a file is read, not with every page that only writes or downloads one.
  const { default: readXlsxFile } = await import("read-excel-file/browser");
  const sheets = await readXlsxFile(buffer);
  return Object.fromEntries(sheets.map((s) => [s.sheet, s.data.map((row) => row.map(cellText))]));
}

export function downloadBlob(blob: Blob, fileName: string) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = fileName;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
