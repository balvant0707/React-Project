// The Excel module of both apps, from COMPASS (app/src/lib/xlsx.ts). Changed: reading goes through read-excel-file (the
// NPM tool's library) instead of COMPASS's unzip and XML reader.
// Writes text tables: bold frozen header, wrapped text, column widths, drop-down validations, an uncompressed archive.

export type SheetSpec = {
  name: string;
  rows: (string | null | undefined)[][];
  // Width per column in characters.
  widths?: number[];
  // First row bold and frozen.
  header?: boolean;
  // Drop-down lists: column index (0-based) and its values (joined, at most 255 characters).
  lists?: { col: number; values: string[] }[];
};

