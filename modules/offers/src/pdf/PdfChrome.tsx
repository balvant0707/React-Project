// Splits composed/free text into bullet points - much more readable than one
// run-on paragraph for a multi-item checklist. Phrase-composed text (see
// SurfacePrepPicker in components/surfacePrepPicker.tsx) is newline-joined, one phrase per
// line - prefer that split when present, since a single phrase can itself
// contain a period (e.g. "min. Sa 2...") that a period-split would wrongly
// treat as a second bullet. Free-typed prose (e.g. plain remarks) has no
// such newlines, so fall back to splitting on sentence-ending periods.
export const splitIntoBullets = (text: string | null | undefined): string[] => {
  const value = text ?? "";
  const parts = value.includes("\n") ? value.split(/\n+/) : value.split(/\.\s+/);
  return parts.map((s) => s.trim()).filter(Boolean);
};

export const BulletList = ({ items }: { items: string[] }) => (
  <View style={styles.bulletList}>
    {items.map((item, i) => (
      <View key={i} style={styles.bulletRow}>
        <Text style={styles.bulletMark}>—</Text>
        <Text style={styles.bulletText}>{item.endsWith(".") ? item : `${item}.`}</Text>
      </View>
    ))}
  </View>
);

export const InfoGrid = ({ items }: { items: { label: string; value: string }[] }) => (
  <View style={styles.infoGrid}>
    {items.map((item, i) => (
      <View key={item.label} style={[styles.infoCell, i >= items.length - (items.length % 2 === 0 ? 2 : 1) ? { borderBottomWidth: 0 } : {}]}>
        <Text style={styles.infoLabel}>{item.label}</Text>
        <Text style={styles.infoValue}>{item.value}</Text>
      </View>
    ))}
  </View>
);

// One field per row rather than InfoGrid's 2-per-row - for use inside a
// letterhead column that is already half the page width, where a 2-per-row
// grid would squeeze each cell to a quarter of the page.
export const InfoList = ({ items }: { items: { label: string; value: string }[] }) => (
  <View style={styles.infoGrid}>
    {items.map((item, i) => (
      <View key={item.label} style={[styles.infoListCell, i === items.length - 1 ? { borderBottomWidth: 0 } : {}]}>
        <Text style={styles.infoLabel}>{item.label}</Text>
        <Text style={styles.infoValue}>{item.value}</Text>
      </View>
    ))}
  </View>
);
